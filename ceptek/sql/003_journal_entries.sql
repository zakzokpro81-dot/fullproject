-- TRIGGER 8: Auto-compute payroll net_salary
-- ============================================================
CREATE OR REPLACE FUNCTION public.compute_payroll_net()
RETURNS trigger AS $$
BEGIN
  NEW.net_salary := NEW.base_salary + NEW.total_allowances - NEW.total_deductions;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

