-- ============================================================
-- 1. fiscal_years
-- ============================================================
CREATE TABLE IF NOT EXISTS public.fiscal_years (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    year_label  text NOT NULL UNIQUE,            -- e.g. '2026'
    start_date  date NOT NULL,
    end_date    date NOT NULL,
    is_closed   boolean NOT NULL DEFAULT false,
    closed_by   bigint REFERENCES public.employees(id) ON DELETE SET NULL,
    closed_at   timestamptz,
    created_at  timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.fiscal_years ENABLE ROW LEVEL SECURITY;
DO $$ BEGIN
  CREATE POLICY "Allow full access for anon" ON public.fiscal_years FOR ALL USING (true) WITH CHECK (true);
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

-- ============================================================
-- 2. journal_entries  (header)
-- ============================================================
CREATE TABLE IF NOT EXISTS public.journal_entries (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_number      text UNIQUE,                -- auto JE-000001
    entry_date        date NOT NULL DEFAULT CURRENT_DATE,
    transaction_type  text NOT NULL DEFAULT 'manual'
                      CHECK (transaction_type IN (
                        'manual','payment','receipt','purchase','expense',
                        'salary','advance','return','adjustment',
                        'opening','closing','transfer'
                      )),
    description       text,
    reference         text,
    source_type       text,                       -- e.g. 'payment','payroll'
    source_id         bigint,                     -- FK to the originating record
    is_posted         boolean NOT NULL DEFAULT false,
    posted_at         timestamptz,
    is_reversed       boolean NOT NULL DEFAULT false,
    reversed_by_id    bigint REFERENCES public.journal_entries(id) ON DELETE SET NULL,
    created_by        bigint REFERENCES public.employees(id) ON DELETE SET NULL,
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.journal_entries ENABLE ROW LEVEL SECURITY;
DO $$ BEGIN
  CREATE POLICY "Allow full access for anon" ON public.journal_entries FOR ALL USING (true) WITH CHECK (true);
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

CREATE INDEX IF NOT EXISTS idx_je_date         ON public.journal_entries(entry_date);
CREATE INDEX IF NOT EXISTS idx_je_type         ON public.journal_entries(transaction_type);
CREATE INDEX IF NOT EXISTS idx_je_posted       ON public.journal_entries(is_posted);
CREATE INDEX IF NOT EXISTS idx_je_source       ON public.journal_entries(source_type, source_id);

DROP TRIGGER IF EXISTS trg_journal_entries_updated_at ON public.journal_entries;
CREATE TRIGGER trg_journal_entries_updated_at
  BEFORE UPDATE ON public.journal_entries
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- ============================================================
-- 3. journal_entry_lines  (detail – debits & credits)
-- ============================================================
CREATE TABLE IF NOT EXISTS public.journal_entry_lines (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journal_entry_id  bigint NOT NULL REFERENCES public.journal_entries(id) ON DELETE CASCADE,
    account_id        bigint NOT NULL REFERENCES public.accounts(id) ON DELETE RESTRICT,
    debit             numeric NOT NULL DEFAULT 0,
    credit            numeric NOT NULL DEFAULT 0,
    description       text,                       -- line-level memo
    cost_center       text,
    created_at        timestamptz NOT NULL DEFAULT now(),
    CHECK ((debit  > 0 AND credit = 0) OR
           (debit  = 0 AND credit > 0))
);

ALTER TABLE public.journal_entry_lines ENABLE ROW LEVEL SECURITY;
DO $$ BEGIN
  CREATE POLICY "Allow full access for anon" ON public.journal_entry_lines FOR ALL USING (true) WITH CHECK (true);
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

CREATE INDEX IF NOT EXISTS idx_jel_entry   ON public.journal_entry_lines(journal_entry_id);
CREATE INDEX IF NOT EXISTS idx_jel_account ON public.journal_entry_lines(account_id);

-- ============================================================
-- TRIGGER 1: Auto-generate entry_number  JE-000001
-- ============================================================
CREATE OR REPLACE FUNCTION public.generate_entry_number()
RETURNS trigger AS $$
DECLARE
  next_num integer;
BEGIN
  SELECT COALESCE(MAX(CAST(SUBSTRING(entry_number FROM 4) AS integer)), 0) + 1
    INTO next_num
    FROM public.journal_entries;
  NEW.entry_number := 'JE-' || LPAD(next_num::text, 6, '0');
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_je_entry_number ON public.journal_entries;
CREATE TRIGGER trg_je_entry_number
  BEFORE INSERT ON public.journal_entries
  FOR EACH ROW
  WHEN (NEW.entry_number IS NULL)
  EXECUTE FUNCTION public.generate_entry_number();

-- ============================================================
-- TRIGGER 2: Validate SUM(debit) = SUM(credit)  (DEFERRED)
-- ============================================================
CREATE OR REPLACE FUNCTION public.validate_journal_balance()
RETURNS trigger AS $$
DECLARE
  total_debit  numeric;
  total_credit numeric;
BEGIN
  SELECT COALESCE(SUM(debit), 0), COALESCE(SUM(credit), 0)
    INTO total_debit, total_credit
    FROM public.journal_entry_lines
   WHERE journal_entry_id = COALESCE(NEW.journal_entry_id, OLD.journal_entry_id);

  IF total_debit <> total_credit THEN
    RAISE EXCEPTION 'Journal entry is not balanced: debit=% credit=%',
      total_debit, total_credit;
  END IF;
  RETURN NULL;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_je_balance_check ON public.journal_entry_lines;
CREATE CONSTRAINT TRIGGER trg_je_balance_check
  AFTER INSERT OR UPDATE OR DELETE ON public.journal_entry_lines
  DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW
  EXECUTE FUNCTION public.validate_journal_balance();

-- ============================================================
-- TRIGGER 3: Recalculate account balances when entry is posted
-- ============================================================
CREATE OR REPLACE FUNCTION public.recalc_account_balances()
RETURNS trigger AS $$
BEGIN
  -- Only act when is_posted changes to true
  IF NEW.is_posted = true AND (OLD.is_posted IS DISTINCT FROM true) THEN
    UPDATE public.accounts a
       SET balance = a.opening_balance + COALESCE(agg.net, 0)
      FROM (
        SELECT jel.account_id,
               SUM(CASE WHEN ac.account_type IN ('asset','expense')
                        THEN jel.debit - jel.credit
                        ELSE jel.credit - jel.debit END) AS net
          FROM public.journal_entry_lines jel
          JOIN public.journal_entries je ON je.id = jel.journal_entry_id
          JOIN public.accounts ac ON ac.id = jel.account_id
         WHERE je.is_posted = true
         GROUP BY jel.account_id
      ) agg
     WHERE a.id = agg.account_id;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_je_recalc_balances ON public.journal_entries;
CREATE TRIGGER trg_je_recalc_balances
  AFTER UPDATE ON public.journal_entries
  FOR EACH ROW EXECUTE FUNCTION public.recalc_account_balances();

-- ============================================================
-- TRIGGER 4: Prevent editing posted entries' lines
-- ============================================================
CREATE OR REPLACE FUNCTION public.prevent_posted_edit()
RETURNS trigger AS $$
DECLARE
  posted boolean;
BEGIN
  SELECT is_posted INTO posted
    FROM public.journal_entries
   WHERE id = COALESCE(OLD.journal_entry_id, NEW.journal_entry_id);

  IF posted = true THEN
    RAISE EXCEPTION 'Cannot modify lines of a posted journal entry';
  END IF;
  RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_jel_prevent_posted ON public.journal_entry_lines;
CREATE TRIGGER trg_jel_prevent_posted
  BEFORE UPDATE OR DELETE ON public.journal_entry_lines
  FOR EACH ROW EXECUTE FUNCTION public.prevent_posted_edit();

-- ============================================================
-- TRIGGER 5: Prevent entries in closed fiscal years
-- ============================================================
CREATE OR REPLACE FUNCTION public.prevent_closed_period()
RETURNS trigger AS $$
DECLARE
  yr_closed boolean;
BEGIN
  SELECT is_closed INTO yr_closed
    FROM public.fiscal_years
   WHERE NEW.entry_date BETWEEN start_date AND end_date
   LIMIT 1;

  IF yr_closed = true THEN
    RAISE EXCEPTION 'Cannot create entries in a closed fiscal period';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_je_closed_period ON public.journal_entries;
CREATE TRIGGER trg_je_closed_period
  BEFORE INSERT ON public.journal_entries
  FOR EACH ROW EXECUTE FUNCTION public.prevent_closed_period();

-- ============================================================
-- TRIGGER 6: Sync invoice paid_amount from payments
-- ============================================================
CREATE OR REPLACE FUNCTION public.sync_invoice_paid_amount()
RETURNS trigger AS $$
DECLARE
  inv_id bigint;
BEGIN
  inv_id := COALESCE(NEW.invoice_id, OLD.invoice_id);
  UPDATE public.invoices
     SET paid_amount = COALESCE((
           SELECT SUM(amount) FROM public.payments WHERE invoice_id = inv_id
         ), 0)
   WHERE id = inv_id;
  RETURN NULL;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_payments_sync ON public.payments;
CREATE TRIGGER trg_payments_sync
  AFTER INSERT OR UPDATE OR DELETE ON public.payments
  FOR EACH ROW EXECUTE FUNCTION public.sync_invoice_paid_amount();

