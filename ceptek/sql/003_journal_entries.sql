-- ============================================================
-- RPC 1: Create journal entry for a payment (customer or supplier)
-- ============================================================
CREATE OR REPLACE FUNCTION public.create_payment_journal_entry(
  p_payment_id  bigint,
  p_source      text        -- 'customer' or 'supplier'
)
RETURNS bigint AS $$
DECLARE
  v_je_id       bigint;
  v_amount      numeric;
  v_account_id  bigint;
  v_description text;
  v_cash_acct   bigint;
  v_recv_acct   bigint;
  v_pay_acct    bigint;
BEGIN
  -- Resolve system accounts
  SELECT id INTO v_cash_acct FROM public.accounts WHERE account_code = '1001' LIMIT 1;
  SELECT id INTO v_recv_acct FROM public.accounts WHERE account_code = '1200' LIMIT 1;
  SELECT id INTO v_pay_acct  FROM public.accounts WHERE account_code = '2100' LIMIT 1;

  IF p_source = 'customer' THEN
    SELECT amount, account_id INTO v_amount, v_account_id
      FROM public.payments WHERE id = p_payment_id;
    v_description := 'Customer payment #' || p_payment_id;

    INSERT INTO public.journal_entries (entry_date, transaction_type, description, source_type, source_id, is_posted, posted_at)
    VALUES (CURRENT_DATE, 'receipt', v_description, 'payment', p_payment_id, true, now())
    RETURNING id INTO v_je_id;

    INSERT INTO public.journal_entry_lines (journal_entry_id, account_id, debit, credit, description)
    VALUES (v_je_id, COALESCE(v_account_id, v_cash_acct), v_amount, 0, 'Cash/Bank received'),
           (v_je_id, v_recv_acct, 0, v_amount, 'Accounts receivable cleared');

  ELSIF p_source = 'supplier' THEN
    SELECT amount, account_id INTO v_amount, v_account_id
      FROM public.supplier_payments WHERE id = p_payment_id;
    v_description := 'Supplier payment #' || p_payment_id;

    INSERT INTO public.journal_entries (entry_date, transaction_type, description, source_type, source_id, is_posted, posted_at)
    VALUES (CURRENT_DATE, 'payment', v_description, 'supplier_payment', p_payment_id, true, now())
    RETURNING id INTO v_je_id;

    INSERT INTO public.journal_entry_lines (journal_entry_id, account_id, debit, credit, description)
    VALUES (v_je_id, v_pay_acct, v_amount, 0, 'Accounts payable cleared'),
           (v_je_id, COALESCE(v_account_id, v_cash_acct), 0, v_amount, 'Cash/Bank paid');
  END IF;

  RETURN v_je_id;
END;
$$ LANGUAGE plpgsql;

-- ============================================================
-- RPC 2: Create journal entry for payroll
-- ============================================================
CREATE OR REPLACE FUNCTION public.create_payroll_journal_entry(p_payroll_id bigint)
RETURNS bigint AS $$
DECLARE
  v_je_id      bigint;
  v_net        numeric;
  v_salary_acct bigint;
  v_cash_acct   bigint;
BEGIN
  SELECT id INTO v_salary_acct FROM public.accounts WHERE account_code = '5100' LIMIT 1;
  SELECT id INTO v_cash_acct   FROM public.accounts WHERE account_code = '1001' LIMIT 1;

  SELECT net_salary INTO v_net FROM public.payroll WHERE id = p_payroll_id;

  INSERT INTO public.journal_entries (entry_date, transaction_type, description, source_type, source_id, is_posted, posted_at)
  VALUES (CURRENT_DATE, 'salary', 'Payroll #' || p_payroll_id, 'payroll', p_payroll_id, true, now())
  RETURNING id INTO v_je_id;

  INSERT INTO public.journal_entry_lines (journal_entry_id, account_id, debit, credit, description)
  VALUES (v_je_id, v_salary_acct, v_net, 0, 'Salary expense'),
         (v_je_id, v_cash_acct,   0, v_net, 'Cash paid');

  RETURN v_je_id;
END;
$$ LANGUAGE plpgsql;

-- ============================================================
-- RPC 3: Reverse a journal entry
-- ============================================================
CREATE OR REPLACE FUNCTION public.reverse_journal_entry(p_entry_id bigint)
RETURNS bigint AS $$
DECLARE
  v_new_id bigint;
  v_orig   record;
BEGIN
  SELECT * INTO v_orig FROM public.journal_entries WHERE id = p_entry_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Entry not found'; END IF;
  IF v_orig.is_reversed THEN RAISE EXCEPTION 'Entry already reversed'; END IF;

  INSERT INTO public.journal_entries (entry_date, transaction_type, description, reference, source_type, source_id, is_posted, posted_at)
  VALUES (CURRENT_DATE, v_orig.transaction_type,
          'Reversal of ' || v_orig.entry_number,
          v_orig.entry_number, v_orig.source_type, v_orig.source_id,
          true, now())
  RETURNING id INTO v_new_id;

  -- Insert swapped lines
  INSERT INTO public.journal_entry_lines (journal_entry_id, account_id, debit, credit, description, cost_center)
  SELECT v_new_id, account_id, credit, debit, 'Reversal: ' || COALESCE(description,''), cost_center
    FROM public.journal_entry_lines
   WHERE journal_entry_id = p_entry_id;

  -- Mark original as reversed
  UPDATE public.journal_entries
     SET is_reversed = true, reversed_by_id = v_new_id
   WHERE id = p_entry_id;

  RETURN v_new_id;
END;
$$ LANGUAGE plpgsql;

-- ============================================================
-- VIEW: Trial Balance
-- ============================================================
CREATE OR REPLACE VIEW public.trial_balance AS
SELECT
  a.id            AS account_id,
  a.account_code,
  a.name          AS account_name,
  a.account_type,
  a.account_subtype,
  COALESCE(SUM(jel.debit), 0)  AS total_debit,
  COALESCE(SUM(jel.credit), 0) AS total_credit,
  CASE WHEN a.account_type IN ('asset','expense')
       THEN a.opening_balance + COALESCE(SUM(jel.debit), 0) - COALESCE(SUM(jel.credit), 0)
       ELSE a.opening_balance + COALESCE(SUM(jel.credit), 0) - COALESCE(SUM(jel.debit), 0)
  END AS balance
FROM public.accounts a
LEFT JOIN public.journal_entry_lines jel ON jel.account_id = a.id
LEFT JOIN public.journal_entries je ON je.id = jel.journal_entry_id AND je.is_posted = true
GROUP BY a.id, a.account_code, a.name, a.account_type, a.account_subtype, a.opening_balance;

-- ============================================================
-- VIEW: Account Ledger  (line-by-line history)
-- ============================================================
CREATE OR REPLACE VIEW public.account_ledger AS
SELECT
  jel.id           AS line_id,
  a.id             AS account_id,
  a.account_code,
  a.name           AS account_name,
  je.id            AS journal_entry_id,
  je.entry_number,
  je.entry_date,
  je.description   AS entry_description,
  jel.debit,
  jel.credit,
  jel.description  AS line_description,
  jel.cost_center
FROM public.journal_entry_lines jel
JOIN public.journal_entries je ON je.id = jel.journal_entry_id
JOIN public.accounts a ON a.id = jel.account_id
WHERE je.is_posted = true
ORDER BY je.entry_date, je.id, jel.id;

