-- ============================================================
-- 1. accounts  (Chart of Accounts)
-- ============================================================
CREATE TABLE IF NOT EXISTS public.accounts (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_code    text NOT NULL UNIQUE,
    name            text NOT NULL,
    account_type    text NOT NULL DEFAULT 'asset'
                    CHECK (account_type IN ('asset','liability','equity','revenue','expense')),
    account_subtype text NOT NULL DEFAULT 'cash'
                    CHECK (account_subtype IN (
                      'cash','bank','receivable','inventory','fixed_asset','other_asset',
                      'payable','accrued','loan','other_liability',
                      'capital','retained_earnings',
                      'sales','service_income','other_revenue',
                      'cost_of_goods','operating','salary','depreciation','other_expense'
                    )),
    parent_id       bigint REFERENCES public.accounts(id) ON DELETE SET NULL,
    description     text,
    opening_balance numeric NOT NULL DEFAULT 0,
    balance         numeric NOT NULL DEFAULT 0,
    is_system       boolean NOT NULL DEFAULT false,
    is_active       boolean NOT NULL DEFAULT true,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.accounts ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow full access for anon" ON public.accounts FOR ALL USING (true) WITH CHECK (true);

CREATE TRIGGER trg_accounts_updated_at
  BEFORE UPDATE ON public.accounts
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

