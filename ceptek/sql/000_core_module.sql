-- 1. accounts (financial accounts: cash, bank)
CREATE TABLE IF NOT EXISTS public.accounts (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL,
    account_type text NOT NULL DEFAULT 'cash'
                CHECK (account_type IN ('cash', 'bank')),
    balance     numeric NOT NULL DEFAULT 0,
    is_active   boolean NOT NULL DEFAULT true,
    created_at  timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.accounts ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow full access for anon" ON public.accounts FOR ALL USING (true) WITH CHECK (true);

-- 2. customer_types
CREATE TABLE IF NOT EXISTS public.customer_types (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_name   text NOT NULL UNIQUE,
    created_at  timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.customer_types ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow full access for anon" ON public.customer_types FOR ALL USING (true) WITH CHECK (true);

-- 3. customers
CREATE TABLE IF NOT EXISTS public.customers (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                text NOT NULL,
    store_name          text,
    email               text,
    phone               text,
    phone2              text,
    address             text,
    tax_number          text,
    notes               text,
    customer_type_id    bigint REFERENCES public.customer_types(id) ON DELETE SET NULL,
    is_active           boolean NOT NULL DEFAULT true,
    created_at          timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.customers ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow full access for anon" ON public.customers FOR ALL USING (true) WITH CHECK (true);

-- 4. invoices
CREATE TABLE IF NOT EXISTS public.invoices (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id         bigint NOT NULL REFERENCES public.customers(id) ON DELETE RESTRICT,
    warehouse_id        bigint REFERENCES public.warehouses(id) ON DELETE SET NULL,
    invoice_number      text,
    invoice_date        timestamptz NOT NULL DEFAULT now(),
    total_amount        numeric NOT NULL DEFAULT 0,
    paid_amount         numeric NOT NULL DEFAULT 0,
    status_id           bigint NOT NULL DEFAULT 1 REFERENCES public.invoice_statuses(id) ON DELETE RESTRICT,
    notes               text,
    created_at          timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.invoices ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow full access for anon" ON public.invoices FOR ALL USING (true) WITH CHECK (true);

-- 5. payments (customer payments)
CREATE TABLE IF NOT EXISTS public.payments (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id          bigint NOT NULL REFERENCES public.invoices(id) ON DELETE RESTRICT,
    account_id          bigint NOT NULL REFERENCES public.accounts(id) ON DELETE RESTRICT,
    amount              numeric NOT NULL,
    date                timestamptz NOT NULL DEFAULT now(),
    method              text NOT NULL DEFAULT 'cash'
                        CHECK (method IN ('cash', 'bank', 'check')),
    notes               text,
    created_by          bigint REFERENCES public.employees(id) ON DELETE SET NULL,
    created_at          timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.payments ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow full access for anon" ON public.payments FOR ALL USING (true) WITH CHECK (true);

