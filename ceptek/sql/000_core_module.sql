-- ============================================================
-- 6. sales_returns (customer / sales returns)
-- ============================================================
CREATE TABLE IF NOT EXISTS public.sales_returns (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id          bigint NOT NULL REFERENCES public.invoices(id) ON DELETE RESTRICT,
    invoice_item_id     bigint REFERENCES public.invoice_items(id) ON DELETE SET NULL,
    return_date         date NOT NULL DEFAULT CURRENT_DATE,
    quantity            integer NOT NULL DEFAULT 1,
    reason              text,
    refund_amount       numeric NOT NULL DEFAULT 0,
    status_id           bigint NOT NULL DEFAULT 1 REFERENCES public.return_statuses(id) ON DELETE RESTRICT,
    created_by          bigint REFERENCES public.employees(id) ON DELETE SET NULL,
    created_at          timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.sales_returns ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow full access for anon" ON public.sales_returns FOR ALL USING (true) WITH CHECK (true);

-- Sales Returns indexes
CREATE INDEX IF NOT EXISTS idx_sales_returns_invoice ON public.sales_returns(invoice_id);
CREATE INDEX IF NOT EXISTS idx_sales_returns_status ON public.sales_returns(status_id);
CREATE INDEX IF NOT EXISTS idx_sales_returns_date ON public.sales_returns(return_date);
