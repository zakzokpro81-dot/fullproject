-- 1. supplier_types
CREATE TABLE IF NOT EXISTS public.supplier_types (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_name   text NOT NULL UNIQUE,
    created_at  timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.supplier_types ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow full access for anon" ON public.supplier_types FOR ALL USING (true) WITH CHECK (true);

-- 2. suppliers
CREATE TABLE IF NOT EXISTS public.suppliers (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                text NOT NULL,
    company_name        text,
    email               text,
    phone               text,
    phone2              text,
    address             text,
    tax_number          text,
    notes               text,
    is_active           boolean NOT NULL DEFAULT true,
    supplier_type_id    bigint REFERENCES public.supplier_types(id) ON DELETE SET NULL,
    created_at          timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.suppliers ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow full access for anon" ON public.suppliers FOR ALL USING (true) WITH CHECK (true);

-- 3. purchase_orders
CREATE TABLE IF NOT EXISTS public.purchase_orders (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id     bigint NOT NULL REFERENCES public.suppliers(id) ON DELETE RESTRICT,
    warehouse_id    bigint REFERENCES public.warehouses(id) ON DELETE SET NULL,
    order_date      timestamptz NOT NULL DEFAULT now(),
    total_amount    numeric NOT NULL DEFAULT 0,
    notes           text,
    status_id       bigint NOT NULL DEFAULT 1 REFERENCES public.order_statuses(id) ON DELETE RESTRICT,
    created_by      bigint REFERENCES public.employees(id) ON DELETE SET NULL,
    created_at      timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.purchase_orders ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow full access for anon" ON public.purchase_orders FOR ALL USING (true) WITH CHECK (true);

-- 4. purchase_order_items
CREATE TABLE IF NOT EXISTS public.purchase_order_items (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id   bigint NOT NULL REFERENCES public.purchase_orders(id) ON DELETE CASCADE,
    product_id          bigint NOT NULL REFERENCES public.products(id) ON DELETE RESTRICT,
    product_unit_id     bigint REFERENCES public.product_units(id) ON DELETE SET NULL,
    quantity            integer NOT NULL DEFAULT 1,
    unit_cost           numeric NOT NULL DEFAULT 0,
    total_cost          numeric NOT NULL DEFAULT 0
);

ALTER TABLE public.purchase_order_items ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow full access for anon" ON public.purchase_order_items FOR ALL USING (true) WITH CHECK (true);

-- 5. purchase_invoices
CREATE TABLE IF NOT EXISTS public.purchase_invoices (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id         bigint NOT NULL REFERENCES public.suppliers(id) ON DELETE RESTRICT,
    purchase_order_id   bigint REFERENCES public.purchase_orders(id) ON DELETE SET NULL,
    invoice_date        timestamptz NOT NULL DEFAULT now(),
