-- 7. supplier_payments
CREATE TABLE IF NOT EXISTS public.supplier_payments (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_invoice_id     bigint NOT NULL REFERENCES public.purchase_invoices(id) ON DELETE RESTRICT,
    account_id              bigint NOT NULL REFERENCES public.accounts(id) ON DELETE RESTRICT,
    payment_date            timestamptz NOT NULL DEFAULT now(),
    amount                  numeric NOT NULL,
    method                  text NOT NULL DEFAULT 'cash'
                            CHECK (method IN ('cash', 'bank', 'check')),
    notes                   text,
    created_by              bigint REFERENCES public.employees(id) ON DELETE SET NULL,
    created_at              timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.supplier_payments ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow full access for anon" ON public.supplier_payments FOR ALL USING (true) WITH CHECK (true);

-- 8. purchase_returns
CREATE TABLE IF NOT EXISTS public.purchase_returns (
    id                          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_invoice_item_id    bigint NOT NULL REFERENCES public.purchase_invoice_items(id) ON DELETE RESTRICT,
