    paid_amount         numeric NOT NULL DEFAULT 0,
    status_id           bigint NOT NULL DEFAULT 1 REFERENCES public.invoice_statuses(id) ON DELETE RESTRICT,
    invoice_number      text,
    notes               text,
    created_by          bigint REFERENCES public.employees(id) ON DELETE SET NULL,
    created_at          timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.purchase_invoices ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow full access for anon" ON public.purchase_invoices FOR ALL USING (true) WITH CHECK (true);

-- 6. purchase_invoice_items
